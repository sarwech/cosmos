def _cells(row):
    """split a table row on the separators we wrote (' | '), not on | inside text"""
    inner = row[1:-1] if row.endswith('|') else row[1:]
    if set(inner.replace('|', '')) <= set('-'):
        return inner.split('|')
    return [' ' + c.strip() + ' ' for c in inner.strip().split(' | ')]



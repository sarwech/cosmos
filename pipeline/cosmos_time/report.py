SURFACE, INK, INK2, GRID = '#fcfcfb', '#0b0b0b', '#52514e', '#e4e3df'
MEMBER, OUTLIER = '#2a78d6', '#eb6834'          # categorical slots 1-2 (validated)
FIGURE = [('Dubhe', 'Merak'), ('Merak', 'Phecda'), ('Phecda', 'Megrez'), ('Megrez', 'Dubhe'),
          ('Megrez', 'Alioth'), ('Alioth', 'Mizar'), ('Mizar', 'Alkaid')]


def _gnomonic(ra, dec, ra0, dec0):
    ra, dec, ra0, dec0 = map(np.radians, (ra, dec, ra0, dec0))
    c = np.sin(dec0) * np.sin(dec) + np.cos(dec0) * np.cos(dec) * np.cos(ra - ra0)
    x = np.cos(dec) * np.sin(ra - ra0) / c
    y = (np.cos(dec0) * np.sin(dec) - np.sin(dec0) * np.cos(dec) * np.cos(ra - ra0)) / c
    return -np.degrees(x), np.degrees(y)                         # east to the left, as on the sky


def dipper_figure(res, path):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    sky = res['4_big_dipper']['sky_radec_deg']
    members = set(res['4_big_dipper']['member_dev_kms'])
    epochs = list(sky)
    ra0 = np.mean([v[0] for v in sky[epochs[0]].values()])
    dec0 = np.mean([v[1] for v in sky[epochs[0]].values()])
    fig, axes = plt.subplots(1, len(epochs), figsize=(12, 3.4), facecolor=SURFACE, sharex=True, sharey=True)
    for ax, ep in zip(axes, epochs):
        pts = {n: _gnomonic(*sky[ep][n], ra0, dec0) for n in sky[ep]}
        ax.set_facecolor(SURFACE)
        for a, b in FIGURE:
            ax.plot([pts[a][0], pts[b][0]], [pts[a][1], pts[b][1]], color='#9a9993', lw=1, zorder=1)
        for n, (x, y) in pts.items():
            col = MEMBER if n in members else OUTLIER
            ax.scatter([x], [y], s=64, color=col, edgecolor=SURFACE, linewidth=2, zorder=3)
            if ep == epochs[0] or n not in members:
                ax.annotate(n, (x, y), xytext=(5, 6), textcoords='offset points', fontsize=8.5, color=INK2)
        title = 'Today (measured)' if ep.startswith('0') else f'+{ep.replace(" kyr", ",000 years")} (simulated)'
        ax.set_title(title, fontsize=10.5, color=INK, loc='left')
        ax.grid(color=GRID, lw=0.6)
        ax.tick_params(colors=INK2, labelsize=8, length=0)
        for s in ax.spines.values():
            s.set_visible(False)
        ax.set_aspect('equal')
        ax.set_xlabel('degrees east ←   → west', fontsize=8.5, color=INK2)
    axes[0].set_ylabel('degrees', fontsize=8.5, color=INK2)
    from matplotlib.lines import Line2D
    h = [Line2D([], [], marker='o', ls='', color=MEMBER, markersize=8, label='Ursa Major moving group (5 stars)'),
         Line2D([], [], marker='o', ls='', color=OUTLIER, markersize=8, label='Dubhe and Alkaid')]
    fig.legend(handles=h, loc='upper right', frameon=False, fontsize=9, labelcolor=INK2, ncol=2)
    fig.suptitle('The Big Dipper falls apart', x=0.01, ha='left', fontsize=12.5, color=INK, weight='bold')
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    fig.savefig(path, dpi=150, facecolor=SURFACE)
    plt.close(fig)


